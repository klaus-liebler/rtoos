// STM32F103 GPIO and AFIO (RM0008 rev 21 chapter 9). The F1 port IP is older than the one
// port/stm32/gpio.hpp drives: one 4-bit field per pin in CRL/CRH (MODE: input or output speed,
// CNF: analog/floating/pull, push-pull/open-drain, GPIO/alternate), the pull direction in ODR,
// no AF numbers. A peripheral signal is on a fixed pin unless its peripheral is moved as a
// group by a field of AFIO_MAPR ("remap"): TIM3_REMAP = 10b moves TIM3_CH1/CH2 to PB4/PB5.
//
// Pin configuration is a compile-time list, like on the newer chips: the compiler folds it into
// one mask and value per port (CRL, CRH, initial ODR levels) and one for AFIO_MAPR, and rejects
// contradictions. Signals are named, and ST's pin database (pin_functions.hpp, generated by
// tools/gen_pin_functions.py) gives for each pin and signal the remap field and the field values
// that put the signal there. Over a list the allowed values of each field are intersected: two
// pins that need different TIM3_REMAP values do not compile, a pin without that signal does not
// compile, a pin the LQFP48 lacks does not compile.
//
//   inline constexpr std::array pins{
//       gpio::output({GpioPort::B, 12}, /*high*/ true),                           // LED off (active low)
//       gpio::alternate({GpioPort::A, 9}, Signal::USART1_TX),
//       gpio::peripheral_input({GpioPort::A, 10}, Signal::USART1_RX, Pull::Up),
//       gpio::peripheral_input({GpioPort::B, 4}, Signal::TIM3_CH1, Pull::Up),      // TIM3 partial remap
//   };
//   gpio::configure<pins>();
//
// Debug port (AFIO_MAPR.SWJ_CFG): PA13/PA14 (SWD) and PA15/PB3/PB4 (JTAG) belong to the debug
// port after reset. A list that uses PA15, PB3 or PB4 switches JTAG off and keeps SWD; one that
// uses PA13 or PA14 switches the whole debug port off. SWJ_CFG is write-only (RM0008 9.4.2: reads
// are undefined), so the driver remembers the strongest setting written so far and never re-opens
// a port a pin list took (configure() of a later list keeps it).
//
// Errata: ES096 2.3.6 "I2C2 with SPI2 and USART3" - while I2C2 is clocked, PB12 as alternate
// function output collides with I2C2_SMBA; PB12 as GPIO is unaffected.
