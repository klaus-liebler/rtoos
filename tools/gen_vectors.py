"""Generate a chip's complete vector table.

Usage: python tools/gen_vectors.py STM32H563.svd > port/stm32h563/src/vectors.cpp
       python tools/gen_vectors.py stm32g431xx.h > port/stm32g431/src/vectors.cpp

STM32H563: from ST's SVD (https://github.com/modm-io/cmsis-svd-stm32, stm32h5/STM32H563.svd,
v1.8). STM32G431: from the IRQn_Type of ST's CMSIS device header
(https://github.com/STMicroelectronics/cmsis_device_g4, Include/stm32g431xx.h) - the G4 SVD
describes the whole family and lists interrupts the G431 does not have (TIM5, UART5, ...).
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

IRQ_COUNT = 131  # RM0481: 131 maskable interrupt lines on STM32H563
G4_IRQ_COUNT = 102  # stm32g431xx.h: the last line is FMAC_IRQn = 101

# Entries missing or misspelled in the SVD (v1.8), fixed per the RM0481 vector table.
OVERRIDES = {
    1: "PVD_AVD",
    2: "RTC",
    3: "RTC_S",
    65: "TIM8_BRK_TERR_IERR",  # SVD: "IM8_BRK_TERR_IERR"
}

# Cortex-M33 system exceptions 1..15 (None = reserved). Reset_Handler, SVC, PendSV and
# SysTick are strong symbols provided by startup.cpp / the kernel port.
CORE = [
    "Reset_Handler", "NMI_Handler", "HardFault_Handler", "MemManage_Handler",
    "BusFault_Handler", "UsageFault_Handler", "SecureFault_Handler", None, None, None,
    "SVC_Handler", "DebugMon_Handler", None, "PendSV_Handler", "SysTick_Handler",
]
# Cortex-M4: no SecureFault (ARMv7-M exception 7 is reserved).
CORE_M4 = [name if name != "SecureFault_Handler" else None for name in CORE]
STRONG = {"Reset_Handler", "SVC_Handler", "PendSV_Handler", "SysTick_Handler"}


def svd_names(path):
    names: dict[int, str] = {}
    for peripheral in ET.parse(path).getroot().iter("peripheral"):
        for irq in peripheral.findall("interrupt"):
            names.setdefault(int(irq.findtext("value")), irq.findtext("name"))
    names.update(OVERRIDES)
    return names


def header_names(path):
    """IRQn_Type entries with a number >= 0: {n: "TIM2"} from "TIM2_IRQn = 28,"."""
    text = Path(path).read_text(encoding="utf-8", errors="replace")
    body = text[text.index("typedef enum"):text.index("} IRQn_Type;")]
    return {int(n): name for name, n in re.findall(r"^\s*(\w+)_IRQn\s*=\s*(\d+)", body, re.M)}


def main() -> None:
    sys.stdout.reconfigure(newline="\n")  # LF on Windows too (.gitattributes)
    source = Path(sys.argv[1])
    if source.suffix == ".h":
        names, irq_count, core = header_names(source), G4_IRQ_COUNT, CORE_M4
    else:
        names, irq_count, core = svd_names(source), IRQ_COUNT, CORE

    o = []
    o += [
        "// SPDX-License-Identifier: MIT",
        f"// GENERATED by tools/gen_vectors.py from {source.name} - do not edit.",
        "//",
        "// Every handler except the kernel's and Reset_Handler is a weak alias of",
        "// Default_Handler; define an extern \"C\" function with the same name to install it.",
        "#include <array>",
        "#include <cstdint>",
        "",
        'extern "C" {',
        "extern std::uint32_t _estack;",
        "",
        "/// Unhandled exception or interrupt: stop in the debugger.",
        "void Default_Handler() noexcept {",
        '    __asm volatile("bkpt #0");',
        "    for (;;) {",
        "    }",
        "}",
        "",
    ]
    for name in core:
        if name is None:
            continue
        if name in STRONG:
            o.append(f"void {name}() noexcept;")
        else:
            o.append(f'void {name}() noexcept __attribute__((weak, alias("Default_Handler")));')
    for i in range(irq_count):
        if i in names:
            o.append(f'void {names[i]}_IRQHandler() noexcept __attribute__((weak, alias("Default_Handler")));')
    o += [
        "}",
        "",
        "namespace {",
        "using Handler = void (*)() noexcept;",
        "",
        "struct VectorTable {",
        "    std::uint32_t* initial_sp;",
        f"    std::array<Handler, {len(core) + irq_count}> handlers;",
        "};",
        "}  // namespace",
        "",
        '[[gnu::section(".isr_vector"), gnu::used]] constinit const VectorTable vector_table{',
        "    &_estack,",
        "    {{",
    ]
    for n, name in enumerate(core, start=1):
        entry = f"&{name}" if name else "nullptr"
        o.append(f"        {entry + ',':<40} // exc {n:3} {name or 'reserved'}")
    for i in range(irq_count):
        entry = f"&{names[i]}_IRQHandler" if i in names else "&Default_Handler"
        o.append(f"        {entry + ',':<40} // irq {i:3} {names.get(i, 'reserved')}")
    o += ["    }},", "};"]
    print("\n".join(o))


if __name__ == "__main__":
    main()
